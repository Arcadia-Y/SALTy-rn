/* Declaration-only interface for signed/unsigned reductions. Real architecture
 * headers are compiled independently; instruction behavior is defined in Lean. */
typedef signed char int8_t;
typedef unsigned char uint8_t;
typedef short int16_t;
typedef unsigned short uint16_t;
typedef int int32_t;
typedef unsigned int uint32_t;
typedef unsigned long size_t;
_Static_assert(sizeof(size_t) == 8 && sizeof(int32_t) == 4, "LP64");
typedef int16_t int16x8_t __attribute__((vector_size(16)));
typedef int32_t int32x4_t __attribute__((vector_size(16)));
typedef int8_t int8x16_t __attribute__((vector_size(16)));
typedef uint16_t uint16x8_t __attribute__((vector_size(16)));
typedef uint32_t uint32x4_t __attribute__((vector_size(16)));
typedef uint8_t uint8x16_t __attribute__((vector_size(16)));
typedef struct { unsigned char opaque; } vint32m1_t;
typedef struct { unsigned char opaque; } vint32m8_t;
typedef struct { unsigned char opaque; } vint8m2_t;
typedef struct { unsigned char opaque; } vuint32m1_t;
typedef struct { unsigned char opaque; } vuint32m8_t;
typedef struct { unsigned char opaque; } vuint8m2_t;
